"""Journal upgrade, phase 3: one generated topology that is structurally
different from src/scaled_models.py's two chains after causalization.

BridgedStar{N}: a hub capacitor Vh fed from a constant source through Rs,
with N identical branches hanging off the hub. Branch k is a resistive
bridge with two internal (non-capacitor) nodes A{k}, B{k}:

    Vh --R1-- A{k} --R2-- B{k} --R3-- V{k} (capacitor C to ground)
               |           |
               Rg          Rg
               |           |
              gnd         gnd

KCL at the internal nodes makes each branch a genuine 5-equation LINEAR
coupled block {I, J, K, A, B} (no state sits inside it to cut the loop),
and the hub's der(Vh) equation reads every branch's inflow I{k} directly
(fan-in N, a star, not a chain). Index-1 by construction: every capacitor
goes to ground and no two capacitors are joined without a resistor
between them, so no capacitor-only loop exists. Linear, no events, no
time-dependent source, so it stays inside what src/block_codegen.py and
src/expr_c.py support.

Equation count: 1 (hub) + 6 per branch = 6N + 1.
Expected units: N coupled 5-blocks + N branch states + 1 hub state = 2N+1.

The hub sum is emitted as a balanced parenthesized tree, not a flat
left-deep I1 + I2 + ... + IN: the codegen and graph helpers recurse over
the expression tree, and a left-deep chain of N terms would hit Python's
default recursion limit near N=1000.
"""
from __future__ import annotations

from pathlib import Path


def _balanced_sum(terms: list[str]) -> str:
    if len(terms) == 1:
        return terms[0]
    mid = len(terms) // 2
    return f"({_balanced_sum(terms[:mid])} + {_balanced_sum(terms[mid:])})"


def generate_bridged_star(n_branches: int, out_path: str | Path) -> Path:
    n = n_branches
    lines = [
        f"model BridgedStar{n}",
        f'  "A hub capacitor with {n} resistive-bridge RC branches, generated by '
        f'src/journal_generators.py."',
        "  parameter Real Vsrc = 1.0;",
        "  parameter Real Rs = 1.0;",
        "  parameter Real R1 = 2.0;",
        "  parameter Real R2 = 3.0;",
        "  parameter Real R3 = 4.0;",
        "  parameter Real Rg = 5.0;",
        "  parameter Real Ch = 0.5;",
        "  parameter Real C = 0.1;",
        "  Real Vh(start=0.0);",
    ]
    for k in range(1, n + 1):
        lines.append(f"  Real V{k}(start=0.0);")
    for k in range(1, n + 1):
        lines.append(f"  Real I{k}; Real J{k}; Real K{k}; Real A{k}; Real B{k};")

    lines.append("equation")
    lines.append(f"  Ch*der(Vh) = (Vsrc - Vh)/Rs - {_balanced_sum([f'I{k}' for k in range(1, n + 1)])};")
    for k in range(1, n + 1):
        lines += [
            f"  I{k} = (Vh - A{k})/R1;",
            f"  J{k} = (A{k} - B{k})/R2;",
            f"  K{k} = (B{k} - V{k})/R3;",
            f"  0 = I{k} - J{k} - A{k}/Rg;",
            f"  0 = J{k} - K{k} - B{k}/Rg;",
            f"  C*der(V{k}) = K{k};",
        ]
    lines.append(f"end BridgedStar{n};")
    lines.append("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def swap_branch_bridge(source_path: str | Path, k: int, out_path: str | Path) -> Path:
    """Branch k's bridge resistor equation divides by 2*R2 instead of R2
    (a genuine formula edit). Seed equation: J{k}. The matcher may assign
    that textual equation to another member of branch k's coupled block;
    every member resolves to the same unit, so the affected-unit set is
    the same either way."""
    text = Path(source_path).read_text(encoding="utf-8")
    old = f"  J{k} = (A{k} - B{k})/R2;\n"
    assert text.count(old) == 1, f"expected J{k} equation line not found"
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text.replace(old, f"  J{k} = (A{k} - B{k})/(2*R2);\n"), encoding="utf-8")
    return out_path
