"""Feature 10: parameterized model generators, scaling from single-digit
to industrial-scale (>=100,000) equation counts, for the model classes
Stage A validated: an N-room thermal chain (src/models/thermal_network's
topology, generalized) and an N-segment RC ladder (src/models/
rlc_circuit's coupling pattern, generalized). Both are index-1 by
construction (no reactive-only loop/cutset is possible in a chain
topology), matching Stage A's scoped generality claim.

Hand-written flat equations, not real MSL component instantiations: a
real MSL Resistor alone carries ~9 equations (heat port, temperature-
dependent resistance, ...) that have nothing to do with what Stage B is
actually testing (scaling behavior of the matching/codegen/build
pipeline), and would multiply Rumoca's own parse/flatten time at
100,000+ equations for no benefit to what's being measured. Stage A's
real-MSL generality claim stands on its own already; Stage B tests scale
on the model classes already proven correct, not generality a second
time.
"""
from __future__ import annotations

from pathlib import Path


def generate_thermal_chain(n_rooms: int, out_path: str | Path) -> Path:
    """N rooms in a chain, room 1 heated, each room i losing heat to
    ambient and exchanging heat with room i+1 -- the exact topology
    src/models/thermal_network/ThermalNetwork.mo already validated
    (causalizes to all-singleton after the Stage A granularity fix, no
    genuine algebraic loop), generalized to N rooms instead of 3.
    Equation count: 3 per room (der(Ti), Qi_env, plus one Qi,i+1 for all
    but the last room) + 1 heater ~= 3N.
    """
    lines = [
        f"model ThermalChain{n_rooms}",
        f'  "A {n_rooms}-room thermal chain, generated by src/scaled_models.py '
        f'for Stage B scaling tests. Same topology as models/thermal_network, '
        f'generalized to N rooms."',
        "  parameter Real Genv = 0.2;",
        "  parameter Real Gadj = 0.5;",
        "  parameter Real Tamb = 15.0;",
        "  parameter Real Qheater = 100.0;",
    ]
    for i in range(1, n_rooms + 1):
        lines.append(f"  parameter Real C{i} = 2.0;")
    for i in range(1, n_rooms + 1):
        lines.append(f"  Real T{i}(start=15.0);")
    for i in range(1, n_rooms + 1):
        lines.append(f"  Real Q{i}env;")
    for i in range(1, n_rooms):
        lines.append(f"  Real Q{i}_{i+1};")

    lines.append("equation")
    lines.append("  Q1env = Genv*(T1 - Tamb);")
    for i in range(2, n_rooms + 1):
        lines.append(f"  Q{i}env = Genv*(T{i} - Tamb);")
    for i in range(1, n_rooms):
        lines.append(f"  Q{i}_{i+1} = Gadj*(T{i} - T{i+1});")

    # der(Ti) = (inflow - outflow - env loss) / Ci
    for i in range(1, n_rooms + 1):
        terms = []
        if i == 1:
            terms.append("Qheater")
        else:
            terms.append(f"Q{i-1}_{i}")
        terms.append(f"- Q{i}env")
        if i < n_rooms:
            terms.append(f"- Q{i}_{i+1}")
        rhs = " ".join(terms)
        lines.append(f"  C{i}*der(T{i}) = {rhs};")

    lines.append(f"end ThermalChain{n_rooms};")
    lines.append("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def generate_rc_ladder(n_segments: int, out_path: str | Path) -> Path:
    """N-segment RC ladder: a chain of N (resistor, capacitor-to-ground)
    stages fed by a shared time-varying source, same coupling flavor as
    models/rlc_circuit (the state at each stage reads the previous
    stage's voltage). Equation count: 1 source + 2 per stage (der(Vi),
    Ii) ~= 2N+1.
    """
    lines = [
        f"model RcLadder{n_segments}",
        f'  "An {n_segments}-segment RC ladder, generated by src/scaled_models.py '
        f'for Stage B scaling tests."',
        "  parameter Real Vamp = 1.0;",
        "  parameter Real omega = 2.0;",
        "  parameter Real R = 10.0;",
        "  parameter Real C = 0.1;",
        "  Real Vs;",
    ]
    for i in range(1, n_segments + 1):
        lines.append(f"  Real V{i}(start=0.0);")
    for i in range(1, n_segments + 1):
        lines.append(f"  Real I{i};")

    lines.append("equation")
    lines.append("  Vs = Vamp*sin(omega*time);")
    for i in range(1, n_segments + 1):
        upstream = "Vs" if i == 1 else f"V{i-1}"
        lines.append(f"  I{i} = ({upstream} - V{i})/R;")
        lines.append(f"  C*der(V{i}) = I{i};")

    lines.append(f"end RcLadder{n_segments};")
    lines.append("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


if __name__ == "__main__":
    import sys

    n = int(sys.argv[1]) if len(sys.argv) > 1 else 10
    kind = sys.argv[2] if len(sys.argv) > 2 else "thermal"
    if kind == "thermal":
        path = generate_thermal_chain(n, f"models/scaled/ThermalChain{n}/ThermalChain{n}.mo")
    else:
        path = generate_rc_ladder(n, f"models/scaled/RcLadder{n}/RcLadder{n}.mo")
    print(f"wrote {path}")
